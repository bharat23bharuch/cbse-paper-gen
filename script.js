/* --- TAB SWITCHING LOGIC --- */
function switchTab(evt, tabId) {
  const tabs = document.querySelectorAll('.section-box');
  const buttons = document.querySelectorAll('.tab-btn');

  tabs.forEach(tab => tab.classList.remove('active'));
  buttons.forEach(btn => btn.classList.remove('active'));

  document.getElementById(tabId).classList.add('active');
  evt.currentTarget.classList.add('active');
}

/* --- DYNAMIC DROPDOWNS FOR TEST GENERATOR TAB --- */
function updateGeneratorSubjects() {
  const cls = document.getElementById("classSelect").value;
  const container = document.getElementById("subjectContainer");
  container.innerHTML = "";
  
  if (academicMatrix[cls]) {
    Object.keys(academicMatrix[cls]).forEach((sub, idx) => {
      const checked = idx === 0 ? "checked" : "";
      container.innerHTML += `<label><input type="checkbox" name="subject" value="${sub}" ${checked}> ${sub}</label>`;
    });
  }
}

/* --- DYNAMIC DROPDOWNS FOR CHAPTER NOTES TAB --- */
function loadNotesSubjects() {
  const cls = document.getElementById("notesClass").value;
  const subSelect = document.getElementById("notesSubject");
  const chapSelect = document.getElementById("notesChapter");

  subSelect.innerHTML = "<option value=''>Select Subject</option>";
  chapSelect.innerHTML = "<option value=''>Select Chapter</option>";
  
  if (academicMatrix[cls]) {
    Object.keys(academicMatrix[cls]).forEach(sub => {
      subSelect.innerHTML += `<option value="${sub}">${sub}</option>`;
    });
  }
}

function loadNotesChapters() {
  const cls = document.getElementById("notesClass").value;
  const sub = document.getElementById("notesSubject").value;
  const chapSelect = document.getElementById("notesChapter");

  chapSelect.innerHTML = "<option value=''>Select Chapter</option>";

  if (academicMatrix[cls] && academicMatrix[cls][sub]) {
    academicMatrix[cls][sub].forEach(chap => {
      chapSelect.innerHTML += `<option value="${chap}">${chap}</option>`;
    });
  }
}

